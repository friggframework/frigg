'use strict';

const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {canonical, digest, semver, compareVersions, validateBundle} = require('./contract.cjs');

const START = '<!-- module-docs:start -->';
const END = '<!-- module-docs:end -->';
const json = value => `${JSON.stringify(value, null, 2)}\n`;

function checkDestination(root, relative) {
    let cursor = path.resolve(root);
    for (const part of relative.split('/')) {
        assert(part && part !== '.' && part !== '..', 'Invalid destination');
        cursor = path.join(cursor, part);
        if (fs.existsSync(cursor)) assert(!fs.lstatSync(cursor).isSymbolicLink(), `Symlink destination: ${relative}`);
    }
    return cursor;
}

function loadReleases(root, id) {
    const base = checkDestination(root, `docs/api-modules/${id}/versions`);
    if (!fs.existsSync(base)) return [];
    return fs.readdirSync(base).sort().map(version => {
        semver(version);
        const filename = checkDestination(root, `docs/api-modules/${id}/versions/${version}/release.json`);
        return JSON.parse(fs.readFileSync(filename, 'utf8'));
    });
}

function projection(releases) {
    const sorted = [...releases].sort((a, b) => compareVersions(b.bundle.manifest.version, a.bundle.manifest.version) || b.bundle.manifest.version.localeCompare(a.bundle.manifest.version));
    const stable = sorted.find(x => x.bundle.manifest.channel === 'stable');
    const current = stable || sorted[0];
    const {manifest: m, catalog} = current.bundle;
    return {
        ...catalog,
        latestStable: stable?.bundle.manifest.version || null,
        docsPath: `/api-modules/${m.id}`,
        versions: sorted.map(x => ({version: x.bundle.manifest.version, channel: x.bundle.manifest.channel,
            digest: x.digest, packageIntegrity: x.packageIntegrity,
            docsPath: `/api-modules/${m.id}/versions/${x.bundle.manifest.version}`})),
    };
}

function landing(record) {
    const {name, identity, compatibility, latestStable} = record;
    const lines = [`<!-- Generated by frigg-module-docs. Edit documentation in api-module-library. -->`, `# ${name}`, '', record.description, '',
        `Package: \`${identity.package}\`.`, '',
        latestStable ? `Latest stable: [${latestStable}](versions/${latestStable}/README.md).` : 'No stable release has been imported. The versions below are prereleases.', '',
        `Declared Frigg compatibility: \`${compatibility.frigg || 'unknown'}\`. Node compatibility: \`${compatibility.node || 'unknown'}\`.`, '',
        'These are declared ranges, not evidence that every version in the range was tested.', '', '## Versions', ''];
    record.versions.forEach(x => lines.push(`- [${x.version}](versions/${x.version}/README.md) (${x.channel})`));
    return `${lines.join('\n')}\n`;
}

function summary(original, records) {
    const startCount = original.split(START).length - 1, endCount = original.split(END).length - 1;
    assert((startCount === 0 && endCount === 0) || (startCount === 1 && endCount === 1), 'Invalid generated navigation markers');
    const block = [START, ...records.map(x => `* [${x.name} — versioned releases](api-modules/${x.identity.id}/README.md)`), END].join('\n');
    if (startCount) {
        assert(original.indexOf(START) < original.indexOf(END), 'Reversed navigation markers');
        return original.slice(0, original.indexOf(START)) + block + original.slice(original.indexOf(END) + END.length);
    }
    assert(original.includes('## 🔌 API Modules'), 'API Modules navigation section not found');
    return original.replace('## 🔌 API Modules', `## 🔌 API Modules\n\n${block}`);
}

// Prepare every write before changing disk, so validation/conflicts cannot leave a
// partially imported release. The workflow commits the whole projection atomically.
function importRelease(root, release, allowedModules, {checkOnly = false} = {}) {
    assert.equal(release.schemaVersion, 1);
    const allowed = allowedModules.find(x => x.package === release.bundle?.manifest?.package);
    assert(allowed, 'Package is not allowlisted');
    validateBundle(release.bundle, allowed);
    assert.equal(release.digest, digest(release.bundle), 'Bundle digest mismatch');
    assert(/^sha512-[A-Za-z0-9+/]+={0,2}$/.test(release.packageIntegrity), 'Missing package integrity');
    const m = release.bundle.manifest;
    const releases = loadReleases(root, m.id);
    releases.forEach(x => {
        validateBundle(x.bundle, allowed);
        assert.equal(x.digest, digest(x.bundle), 'Stored bundle digest mismatch');
    });
    const existing = releases.find(x => x.bundle.manifest.version === m.version);
    if (existing) assert.equal(canonical(existing), canonical(release), 'Conflicting immutable release; use an explicit docs revision');
    else releases.push(release);

    const writes = new Map();
    const set = (relative, content) => writes.set(checkDestination(root, relative), Buffer.isBuffer(content) ? content : Buffer.from(content));
    const versionDir = `docs/api-modules/${m.id}/versions/${m.version}`;
    const stored = path.join(root, versionDir);
    if (!existing) assert(!fs.existsSync(stored), 'Version directory exists without a release manifest');
    for (const [name, file] of Object.entries(release.bundle.files)) {
        const content = Buffer.from(file.content, file.encoding);
        const relative = `${versionDir}/${name}`;
        const destination = checkDestination(root, relative);
        if (existing) assert(fs.existsSync(destination) && fs.readFileSync(destination).equals(content), 'Stored release content was modified');
        set(relative, content);
    }
    set(`${versionDir}/release.json`, json(release));
    const record = projection(releases);
    const landingPath = checkDestination(root, `docs/api-modules/${m.id}/README.md`);
    let page = landing(record);
    if (fs.existsSync(landingPath)) {
        const original = fs.readFileSync(landingPath, 'utf8');
        if (!original.startsWith('<!-- Generated by frigg-module-docs.')) {
            const start = '<!-- module-release-links:start -->', end = '<!-- module-release-links:end -->';
            assert(original.split(start).length === 2 && original.split(end).length === 2 && original.indexOf(start) < original.indexOf(end), 'Legacy landing page needs an explicit migration');
            page = original.slice(0, original.indexOf(start) + start.length) + '\n' + page.replace(`# ${record.name}\n`, '## Released module versions\n') + original.slice(original.indexOf(end));
        }
    }
    set(`docs/api-modules/${m.id}/README.md`, page);
    set(`website/data/catalog/${m.id}.json`, json(record));

    const records = allowedModules.flatMap(entry => {
        if (entry.id === m.id) return [record];
        const filename = checkDestination(root, `website/data/catalog/${entry.id}.json`);
        return fs.existsSync(filename) ? [JSON.parse(fs.readFileSync(filename, 'utf8'))] : [];
    }).sort((a, b) => a.identity.id.localeCompare(b.identity.id));
    set('website/data/catalog/index.json', json(records));
    const summaryPath = checkDestination(root, 'docs/SUMMARY.md');
    set('docs/SUMMARY.md', summary(fs.readFileSync(summaryPath, 'utf8'), records));

    let changed = 0;
    for (const [filename, content] of writes) {
        if (fs.existsSync(filename) && fs.readFileSync(filename).equals(content)) continue;
        changed++;
        if (checkOnly) continue;
        fs.mkdirSync(path.dirname(filename), {recursive: true});
        fs.writeFileSync(filename, content);
    }
    return {changed, id: m.id, version: m.version};
}

module.exports = {importRelease, projection, summary, checkDestination, loadReleases};

if (require.main === module) {
    const [releasePath] = process.argv.slice(2);
    assert(releasePath, 'Usage: node tools/module-docs/import.cjs release.json');
    console.log(importRelease(process.cwd(), JSON.parse(fs.readFileSync(releasePath, 'utf8')), require('./modules.json')));
}
